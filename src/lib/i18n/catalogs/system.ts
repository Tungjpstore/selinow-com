/** Normalize shared presentation hints with the platform-wide English fallback. */
export function resolvePresentationLocale(value: unknown): SupportedLocale {
  return normalizeSupportedLocale(value);
}

export function createSystemTranslator(locale: unknown) {
  return createTranslator(systemCatalogs, resolvePresentationLocale(locale));
}

